def get_profile_rate(name):
    """Look up profile rate, adding NOTCHED_PREMIUM if applicable."""
    import re
    name_upper = name.strip().upper()
    # normalise "(STRAIGHT)" / "(NOTCHED)" → "STRAIGHT" / "NOTCHED"
    name_upper = re.sub(r'\(\s*(STRAIGHT|NOTCHED)\s*\)', lambda m: m.group(1), name_upper).strip()

    is_notched  = name_upper.endswith(" NOTCHED")
    is_straight = name_upper.endswith(" STRAIGHT")

    if is_notched:
        base = name_upper[:-len(" NOTCHED")].strip()
    elif is_straight:
        base = name_upper[:-len(" STRAIGHT")].strip()
    else:
        base = name_upper

    if base not in PROFILE_RATES:
        return None

    rate = PROFILE_RATES[base]
    if is_notched:
        rate += NOTCHED_PREMIUM
    return rate


def read_chargeable_area(areas_ws):
    total_row = None
    for row in areas_ws.iter_rows():
        for cell in row:
            if cell.value and str(cell.value).strip().lower() == "total":
                total_row = cell.row
                break
        if total_row:
            break

    if not total_row:
        return 0

    header_row = None
    for row in areas_ws.iter_rows(max_row=total_row - 1):
        for cell in row:
            if cell.value and "area" in str(cell.value).lower():
                header_row = cell.row
                break
        if header_row:
            break

    if not header_row:
        return 0

    chargeable_col = None
    fallback_col   = None
    for cell in areas_ws[header_row]:
        if cell.value:
            col_name = str(cell.value).lower()
            if "chargeable" in col_name or "chg" in col_name:
                chargeable_col = cell.column
            elif "area" in col_name:
                fallback_col = cell.column

    col = chargeable_col or fallback_col
    return areas_ws.cell(row=total_row, column=col).value or 0 if col else 0


def _parse_bom_rows(ws, min_row=4):
    bom = []
    for row in ws.iter_rows(min_row=min_row, values_only=True):
        item = row[0]
        qty  = row[1] if len(row) > 1 else 0
        unit = row[2] if len(row) > 2 else ""
        if item:
            try:
                qty_val = float(qty) if qty is not None else 0
            except (TypeError, ValueError):
                qty_val = 0
            bom.append({
                "description": str(item).strip(),
                "qty":         qty_val,
                "unit":        str(unit or "").strip(),
            })
    return bom


def read_bom(bom_ws):
    return _parse_bom_rows(bom_ws, min_row=4)


def read_lights_bom(wb):
    try:
        return _parse_bom_rows(wb.worksheets[2], min_row=4)
    except IndexError:
        return []


def generate_lights_df(lights_bom):
    df = []
    total_light_meters = 0
    for item in lights_bom:
        name = PRODUCT_CATALOG[item["description"]]["description"]
        qty  = item["qty"]
        unit = item["unit"] or "nos"
        rate = PRODUCT_CATALOG[item["description"]]["price"]
        df.append([name, qty, unit, rate])
        if "light" in name.lower():
            total_light_meters += qty

    if total_light_meters:
        df.append(["Installation Charges", total_light_meters, "m", 150])

    return df
